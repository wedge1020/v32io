// End-to-end test, program side. Acts as the cart (and as the frame loop of the
// emulator): per frame it does what V32Console::RunNextFrame does around the CPU
//   SyncMemoryCardMailbox()  ->  "program runs"  ->  SaveMemoryCard()
// and the "program" talks to the card ONLY through the card's memory interface.
// A separate process (dev_e2e_host.py) is the external host.
//
// usage: dev_e2e_cart <card.memc> <messages per channel> <microseconds per frame>
#include "tcommon.hpp"
#include <chrono>
#include <deque>
#include <memory>
#include <unistd.h>

static V32MemoryCardController* Card;
static const int RING = DEV::RingWords;
static const uint32_t KEY_BASE = 0x01010101u;

static int32_t HP( int c ) { return DEV::HostAreaStart + c * DEV::PartWords; }
static int32_t CP( int c ) { return DEV::CartAreaStart + c * DEV::PartWords; }

static uint32_t rd( int32_t w )
{
    V32Word r;
    if( !Card->ReadAddress( w, r ) ) { printf( "bad read %d\n", w ); exit( 3 ); }
    return r.AsBinary;
}

static void wr( int32_t w, uint32_t v )
{
    V32Word x; x.AsBinary = v;
    if( !Card->WriteAddress( w, x ) ) { printf( "bad write %d\n", w ); exit( 3 ); }
}

static vector< uint32_t > Frame( uint32_t opcode, const vector< uint32_t >& payload )
{
    vector< uint32_t > m;
    m.push_back( (uint32_t)payload.size() );
    m.push_back( opcode );
    m.insert( m.end(), payload.begin(), payload.end() );
    return m;
}

// deterministic stream generated by the program (the host regenerates the same)
static uint32_t Gen( int c, int k, int i )
{
    return (((uint32_t)(c + 1) * 0x9E3779B1u * (uint32_t)(k + 1))) ^ ((uint32_t)i * 2654435761u);
}

static vector< uint32_t > StreamMessage( int c, int k )
{
    int len = (k * 7 + c * 3) % 60 + 1;
    vector< uint32_t > payload;
    for( int i = 0; i < len; i++ ) payload.push_back( Gen( c, k, i ) );
    return Frame( 0x4000 + c, payload );
}

int main( int argc, char** argv )
{
    if( argc < 4 ) { printf( "usage\n" ); return 2; }
    string Path = argv[ 1 ];
    int M = atoi( argv[ 2 ] );
    int FrameMicros = atoi( argv[ 3 ] );

    InstallCallbacks();
    std::unique_ptr< V32Console > ConsoleHeap( new V32Console );
    V32Console& Console = *ConsoleHeap;
    Console.LoadMemoryCard( Path );

    if( !Console.HasMemoryCardMailbox() ) { printf( "CART: mailbox not active\n" ); return 2; }
    Card = &Console.MemoryCardController;

    // a program can tell that the emulator keeps the mailbox live
    if( rd( DEV::RegionStart + DEV::H_EmulatorFlags ) != (uint32_t)DEV::EmuFlagLive ) { printf( "CART: no live flag\n" ); return 2; }

    std::deque< vector< uint32_t > > OutQ[ DEV::Channels ];
    vector< uint32_t > InBuf[ DEV::Channels ];
    int NextK[ DEV::Channels ] = { 0 };
    int Echoed[ DEV::Channels ] = { 0 };
    long BadFrames = 0;
    bool Bye = false, AckQueued = false;
    int ExtraFrames = -1;
    long Frames = 0;
    auto Start = std::chrono::steady_clock::now();

    // like the v32dev library: a channel is opened once its host says it is attached,
    // and opening discards whatever the rings held (each side moves the end it owns)
    bool Open[ DEV::Channels ] = { false };

    for( ;; )
    {
        // ---- frame start (what RunNextFrame does first)
        Console.SyncMemoryCardMailbox();
        Frames++;

        // ---- the program runs
        for( int c = 0; c < DEV::Channels; c++ )
        {
            if( !Open[ c ] )
            {
                if( (rd( HP( c ) + 1 ) & 1) == 0 ) continue;
                wr( CP( c ) + 2, rd( HP( c ) + 3 ) );          // h2c tail := host head
                wr( CP( c ) + 1, rd( HP( c ) + 4 ) );          // c2h head := host tail
                wr( CP( c ) + 0, 1 );
                wr( CP( c ) + 4, rd( CP( c ) + 4 ) + 1 );      // session
                Open[ c ] = true;
            }

            // receive: take everything the host has published
            uint32_t Head = rd( HP( c ) + 3 );
            uint32_t Tail = rd( CP( c ) + 2 );

            if( Head >= (uint32_t)RING || Tail >= (uint32_t)RING ) { printf( "CART: corrupt indices\n" ); return 1; }

            if( Head != Tail )
            {
                int Count = (Head + RING - Tail) % RING;
                for( int i = 0; i < Count; i++ )
                  InBuf[ c ].push_back( rd( HP( c ) + DEV::ControlWords + (Tail + i) % RING ) );
                wr( CP( c ) + 2, Head );
            }

            // parse complete messages
            for( ;; )
            {
                vector< uint32_t >& B = InBuf[ c ];
                if( B.size() < 2 ) break;
                uint32_t N = B[ 0 ];
                if( N > (uint32_t)RING - 4 ) { BadFrames++; B.erase( B.begin() ); continue; }
                if( B.size() < N + 2 ) break;

                vector< uint32_t > Msg( B.begin(), B.begin() + N + 2 );
                B.erase( B.begin(), B.begin() + N + 2 );

                uint32_t Opcode = Msg[ 1 ];

                if( Opcode == 0x0FFF )
                  Bye = true;
                else
                {
                    vector< uint32_t > Payload( Msg.begin() + 2, Msg.end() );
                    for( size_t i = 0; i < Payload.size(); i++ ) Payload[ i ] ^= KEY_BASE * (uint32_t)(c + 1);
                    OutQ[ c ].push_back( Frame( Opcode | 0x8000, Payload ) );
                    Echoed[ c ]++;
                }
            }

            // the program also produces its own stream of messages
            if( NextK[ c ] < M && OutQ[ c ].size() < 3 )
              OutQ[ c ].push_back( StreamMessage( c, NextK[ c ]++ ) );
        }

        // once the host said bye and everything is sent, report totals
        bool AllStreamed = true;
        for( int c = 0; c < DEV::Channels; c++ ) if( NextK[ c ] < M ) AllStreamed = false;

        if( Bye && AllStreamed && !AckQueued )
        {
            vector< uint32_t > Totals;
            for( int c = 0; c < DEV::Channels; c++ ) Totals.push_back( (uint32_t)Echoed[ c ] );
            OutQ[ 0 ].push_back( Frame( 0x2FFE, Totals ) );
            AckQueued = true;
        }

        // send: data words first, then the head index
        for( int c = 0; c < DEV::Channels; c++ )
          while( Open[ c ] && !OutQ[ c ].empty() )
          {
              const vector< uint32_t >& Msg = OutQ[ c ].front();
              uint32_t HostTail = rd( HP( c ) + 4 );
              uint32_t MyHead = rd( CP( c ) + 1 );
              uint32_t Free = (HostTail + RING - MyHead - 1) % RING;
              if( Msg.size() > Free ) break;

              for( size_t i = 0; i < Msg.size(); i++ )
                wr( CP( c ) + DEV::ControlWords + (MyHead + i) % RING, Msg[ i ] );
              wr( CP( c ) + 1, (MyHead + Msg.size()) % RING );
              OutQ[ c ].pop_front();
          }

        // ---- frame end (what RunNextFrame does last)
        if( Console.WasMemoryCardModified() )
          Console.SaveMemoryCard();

        // finish a little after the final report went out
        bool Drained = true;
        for( int c = 0; c < DEV::Channels; c++ ) if( !OutQ[ c ].empty() ) Drained = false;
        if( FrameMicros == 0 ) usleep( 50 );          // do not spin at full speed while waiting for a host

        if( AckQueued && Drained )
        {
            if( ExtraFrames < 0 ) ExtraFrames = 40;
            else if( --ExtraFrames == 0 ) break;
        }

        double Seconds = std::chrono::duration< double >( std::chrono::steady_clock::now() - Start ).count();
        if( Seconds > 180 ) { printf( "CART: timeout after %ld frames\n", Frames ); return 1; }

        if( FrameMicros > 0 ) usleep( FrameMicros );
    }

    printf( "CART: done after %ld frames; echoed %d/%d/%d/%d; bad frames %ld\n", Frames, Echoed[ 0 ], Echoed[ 1 ], Echoed[ 2 ], Echoed[ 3 ], BadFrames );

    // the heartbeat only lives in memory: it never reaches the file
    bool BeatNotInFile = (FileWord( Path, DEV::RegionStart + DEV::H_EmulatorBeat ) == 0);
    Console.UnloadMemoryCard();

    if( !BeatNotInFile ) { printf( "CART: heartbeat leaked to file\n" ); return 1; }
    for( int c = 0; c < DEV::Channels; c++ ) if( Echoed[ c ] != M ) { printf( "CART: channel %d echoed %d, expected %d\n", c, Echoed[ c ], M ); return 1; }
    return BadFrames ? 1 : 0;
}
