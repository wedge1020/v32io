#!/usr/bin/env python3
"""
Generates the character tables of v32io from the one definition of the
Vircon32 BIOS font that they all share:

    firmware/RP2350-USB-A/src/compose_table.h   tables used by compose.c
    docs/v32io/COMPOSE.md                       how to type those characters
    (stdout, with --emulator)                   the Unicode -> BIOS table used
                                                by emulator/v32io/v32io.patch

The BIOS font is Windows-1252 (code page 1252), except that

  * codes 0x00-0x08, 0x0B, 0x0C and 0x7F, and the 5 codes cp1252 leaves
    undefined (0x81 0x8D 0x8F 0x90 0x9D), have no glyph, and neither has
    0xA0 (no-break space): "not used", always empty;
  * 0x09, 0x0A and 0x0D are whitespace;
  * 0x0E-0x1F, control codes in cp1252, hold box drawing characters (0x10
    is empty).

Only the Python standard library is needed:   python3 tools/gen-charset.py
"""
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ---------------------------------------------------------------- the BIOS font
GLYPHS = {              # code -> Unicode, for the box drawing range
    0x0E: 0x2B1A, 0x0F: 0x25AF,
    0x11: 0x2591, 0x12: 0x2592, 0x13: 0x2593, 0x14: 0x2588,
    0x15: 0x2500, 0x16: 0x2502, 0x17: 0x2518, 0x18: 0x2510,
    0x19: 0x250C, 0x1A: 0x2514, 0x1B: 0x251C, 0x1C: 0x2524,
    0x1D: 0x2534, 0x1E: 0x252C, 0x1F: 0x253C,
}
UNUSED_HIGH = {0x81, 0x8D, 0x8F, 0x90, 0x9D, 0xA0}


def high_unicode(code):
    """Unicode of BIOS character 0x80-0xFF, or None if the font has none."""
    if code in UNUSED_HIGH:
        return None
    try:
        return ord(bytes([code]).decode("cp1252"))
    except UnicodeDecodeError:
        return None


def code_of(ch):
    """BIOS code of a Unicode character, or None."""
    cp = ord(ch)
    if 0x20 <= cp <= 0x7E:
        return cp
    for code, u in GLYPHS.items():
        if u == cp:
            return code
    try:
        code = ch.encode("cp1252")[0]
    except UnicodeEncodeError:
        return None
    return code if code >= 0x80 and high_unicode(code) == cp else None


def valid(code):
    """Can this BIOS code be sent as a typed character (and typed with an Alt code)?"""
    return (code in GLYPHS or 0x20 <= code <= 0x7E
            or (0x80 <= code <= 0xFF and high_unicode(code) is not None))


# ---------------------------------------------------------------- dead keys
DEADS = [   # name, standalone accent, combining mark, how it is typed
    ("ACUTE",      "´", "́", "AltGr + '"),
    ("GRAVE",      "`",      "̀", "AltGr + `"),
    ("CIRCUMFLEX", "^",      "̂", "AltGr + Shift + 6"),
    ("DIAERESIS",  "¨", "̈", "AltGr + Shift + '"),
    ("TILDE",      "~",      "̃", "AltGr + Shift + `"),
]


def pairs():
    out = []
    for i, (name, _standalone, mark, _how) in enumerate(DEADS, start=1):
        for base in "AEIOUYANOaeiouyano":
            composed = unicodedata.normalize("NFC", base + mark)
            if len(composed) == 1 and code_of(composed) and code_of(composed) >= 0x80:
                out.append((i, name, base, composed, code_of(composed)))
    seen, uniq = set(), []
    for p in out:
        if (p[0], p[2]) not in seen:
            seen.add((p[0], p[2]))
            uniq.append(p)
    return uniq


# ---------------------------------------------------------------- AltGr layer
# HID key name (without HID_KEY_), unshifted character, shifted character
# (None: same as unshifted). Modelled on the US-International layout.
DIRECT = [
    ("1", "¡", "¹"), ("2", "²", None), ("3", "³", None), ("4", "¤", "£"),
    ("5", "€", None), ("6", "¼", None), ("7", "½", None), ("8", "¾", None),
    ("9", "‘", "“"), ("0", "’", "”"), ("MINUS", "¥", "±"), ("EQUAL", "×", "÷"),
    ("Q", "ä", "Ä"), ("W", "å", "Å"), ("E", "é", "É"), ("R", "®", None),
    ("T", "þ", "Þ"), ("Y", "ü", "Ü"), ("U", "ú", "Ú"), ("I", "í", "Í"),
    ("O", "ó", "Ó"), ("P", "ö", "Ö"), ("BRACKET_LEFT", "«", None),
    ("BRACKET_RIGHT", "»", None), ("BACKSLASH", "¬", "¦"),
    ("A", "á", "Á"), ("S", "ß", "§"), ("D", "ð", "Ð"), ("L", "ø", "Ø"),
    ("SEMICOLON", "¶", "°"),
    ("Z", "æ", "Æ"), ("C", "©", "¢"), ("N", "ñ", "Ñ"), ("M", "µ", None),
    ("COMMA", "ç", "Ç"), ("SLASH", "¿", None),
]


def key_label(name):
    return {"MINUS": "-", "EQUAL": "=", "BRACKET_LEFT": "[", "BRACKET_RIGHT": "]",
            "BACKSLASH": "\\", "SEMICOLON": ";", "COMMA": ",", "SLASH": "/"}.get(name, name)


def c_code(code):
    return "0x%02X" % code


# ---------------------------------------------------------------- outputs
def make_header():
    L = []
    w = L.append
    w("// GENERATED by tools/gen-charset.py: do not edit by hand.")
    w("//")
    w("// Character tables for compose.c: what the AltGr layer, the dead keys and")
    w("// the Alt codes can type. Every value is a character code of the Vircon32")
    w("// BIOS font (Windows-1252, with box drawing characters in 0x0E-0x1F).")
    w("")
    w("#ifndef COMPOSE_TABLE_H_")
    w("#define COMPOSE_TABLE_H_")
    w("")
    w("// dead keys")
    w("enum { DEAD_NONE = 0, " + ", ".join("DEAD_%s" % d[0] for d in DEADS) + " };")
    w("")
    w("// the character a dead key types by itself (dead key followed by space,")
    w("// by itself, or by something it can't be combined with)")
    w("static const uint8_t compose_dead_char[] =")
    w("{")
    w("    0,")
    for d in DEADS:
        w("    %s,  // %s %s" % (c_code(code_of(d[1])), d[0].lower(), d[1]))
    w("};")
    w("")
    w("// dead key + letter")
    w("typedef struct { uint8_t dead; char base; uint8_t code; } compose_pair_t;")
    w("static const compose_pair_t compose_pairs[] =")
    w("{")
    for dead, name, base, comp, code in pairs():
        w("    { DEAD_%-10s '%s', %s },  // %s" % (name + ",", base, c_code(code), comp))
    w("};")
    w("")
    w("// AltGr + key (code_shifted is the code with shift held)")
    w("typedef struct { uint8_t usage; uint8_t code; uint8_t code_shifted; } compose_altgr_t;")
    w("static const compose_altgr_t compose_altgr[] =")
    w("{")
    for name, plain, shifted in DIRECT:
        pc = code_of(plain)
        sc = code_of(shifted) if shifted else pc
        assert pc and sc, (name, plain, shifted)
        w("    { HID_KEY_%-14s %s, %s },  // %s %s" % (name + ",", c_code(pc), c_code(sc),
                                                      plain, shifted or ""))
    w("};")
    w("")
    w("// characters that can be typed with an Alt code: bit n of word n/32 means")
    w("// code n has a glyph in the BIOS font and can be sent")
    words = [0] * 8
    for code in range(256):
        if valid(code):
            words[code // 32] |= 1 << (code % 32)
    w("static const uint32_t compose_valid[8] =")
    w("{")
    for i in range(0, 8, 2):
        w("    0x%08X, 0x%08X," % (words[i], words[i + 1]))
    w("};")
    w("")
    w("#endif")
    return "\n".join(L) + "\n"


def make_doc():
    L = []
    w = L.append
    w("# Typing special characters (v32io adapter)")
    w("")
    w("*Generated by `tools/gen-charset.py`; the tables are in `firmware/RP2350-USB-A/src/compose_table.h`.*")
    w("")
    w("A USB keyboard only tells the adapter *which key* was pressed, not what the")
    w("computer's keyboard layout makes of it, so the adapter has its own way of typing")
    w("the characters of the Vircon32 BIOS font that are not on a US keyboard. It is")
    w("meant for a US layout, and it works with the **right Alt** key (AltGr; right")
    w("Option on a Mac) and with **Alt codes** on the numeric keypad. Everything else")
    w("(letters, numbers, shift...) is unchanged, and so is any program that")
    w("doesn't read typed characters.")
    w("")
    w("The right Alt and left Alt keys are still reported to the program as keys.")
    w("Only the keys *typed together with them*, when they type something here, are")
    w("kept from being reported as keys (otherwise `AltGr` `e` would type both `é`")
    w("and `e`). A combination that is not listed below works as it always did.")
    w("")
    w("## AltGr + key")
    w("")
    w("Modelled on the US-International layout. A second column shows what the same")
    w("key types with Shift held; `-` means shift changes nothing.")
    w("")
    w("| Key | AltGr | AltGr + Shift |")
    w("| --- | ----- | ------------- |")
    for name, plain, shifted in DIRECT:
        w("| `%s` | %s (%s) | %s |" % (key_label(name), plain, c_code(code_of(plain)),
                                       ("%s (%s)" % (shifted, c_code(code_of(shifted)))) if shifted else "-"))
    w("")
    w("## Dead keys")
    w("")
    w("Press the dead key combination, release it, then press a letter: the accent is")
    w("put on it (hold Shift for a capital letter, or have Caps Lock on).")
    w("The same dead key twice, or a dead key followed by space, types the accent")
    w("itself; followed by a letter that can't take it, you get the accent and then")
    w("the letter.")
    w("")
    w("| Dead key | Typed with | Letters it combines with |")
    w("| -------- | ---------- | ------------------------ |")
    for i, (name, standalone, _mark, how) in enumerate(DEADS, start=1):
        letters = "".join(p[3] for p in pairs() if p[0] == i)
        w("| %s `%s` | %s | %s |" % (name.lower(), standalone, how, letters))
    w("")
    w("## Alt codes")
    w("")
    w("Hold the **left** Alt key, type the character's decimal code on the **numeric")
    w("keypad** (up to 4 digits; leading zeros are fine), then release Alt. This works")
    w("for every character of the BIOS font, including the box drawing ones, with the")
    w("code of the table below (`Alt` `0` `2` `3` `3` types `é`). A code that has no")
    w("glyph types nothing.")
    w("")
    w("| Code | Character | Code | Character | Code | Character | Code | Character |")
    w("| ---- | --------- | ---- | --------- | ---- | --------- | ---- | --------- |")
    codes = [c for c in range(256) if valid(c) and (c >= 0x80 or c in GLYPHS)]
    rows = (len(codes) + 3) // 4
    for r in range(rows):
        cells = []
        for col in range(4):
            i = col * rows + r
            if i < len(codes):
                c = codes[i]
                ch = chr(GLYPHS[c]) if c in GLYPHS else chr(high_unicode(c))
                cells.append("%d | %s" % (c, ch))
            else:
                cells.append(" | ")
        w("| " + " | ".join(cells) + " |")
    w("")
    w("The codes 32 to 126 (ASCII) also work, and anything else (0 to 13, 16, 127 and")
    w("the codes the BIOS font does not use) types nothing.")
    w("")
    w("On the emulator side none of this is needed: the host operating system's own")
    w("keyboard layout, dead keys and compose keys type the characters (see")
    w("`emulator/v32io/README.md`).")
    return "\n".join(L) + "\n"


def make_emulator_table():
    entries = []
    for code in sorted(GLYPHS):
        entries.append((GLYPHS[code], code))
    for code in range(0x80, 0x100):
        u = high_unicode(code)
        if u is not None:
            entries.append((u, code))
    entries = sorted(set(entries))
    L = []
    for u, code in entries:
        L.append("    { 0x%04X, 0x%02X }," % (u, code))
    return "\n".join(L) + "\n"


def main():
    if "--emulator" in sys.argv:
        sys.stdout.write(make_emulator_table())
        return
    with open(os.path.join(ROOT, "firmware/RP2350-USB-A/src/compose_table.h"), "w") as f:
        f.write(make_header())
    with open(os.path.join(ROOT, "docs/v32io/COMPOSE.md"), "w") as f:
        f.write(make_doc())
    print("wrote compose_table.h and COMPOSE.md")


if __name__ == "__main__":
    main()
